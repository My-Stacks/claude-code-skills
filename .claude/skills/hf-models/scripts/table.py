#!/usr/bin/env python3
"""Generate the model catalogue table for REFERENCE.md from live router data.

Reads /v1/models on stdin, writes markdown to stdout. Regenerate with:
    hf.sh table > /tmp/t.md   (then paste, or hf.sh table --write)
"""
import datetime
import json
import sys

TIERS = [
    ("Budget — under $0.10 in", 0.0, 0.10),
    ("Cheap — $0.10 to $0.50 in", 0.10, 0.50),
    ("Mid — $0.50 to $1.50 in", 0.50, 1.50),
    ("Frontier — over $1.50 in", 1.50, float("inf")),
]


def summarise(m):
    """Cheapest priced provider, plus best-in-class facts across all providers."""
    priced = [p for p in m.get("providers", []) if (p.get("pricing") or {}).get("input") is not None]
    if not priced:
        return None
    cheap = min(priced, key=lambda p: (p["pricing"]["input"], p["pricing"].get("output") or 0))
    tps = [p.get("throughput") for p in m.get("providers", []) if p.get("throughput")]
    ctxs = [p.get("context_length") for p in m.get("providers", []) if p.get("context_length")]
    arch = m.get("architecture") or {}
    return {
        "id": m["id"],
        "prov": cheap.get("provider") or "?",
        "in": cheap["pricing"]["input"],
        "out": cheap["pricing"].get("output"),
        "ctx": max(ctxs) if ctxs else None,
        "tps": max(tps) if tps else None,
        "vision": "image" in (arch.get("input_modalities") or []),
        "tools": any(p.get("supports_tools") for p in m.get("providers", [])),
        "struct": any(p.get("supports_structured_output") for p in m.get("providers", [])),
        "struct_all": all(p.get("supports_structured_output") is not False for p in priced),
    }


def fmt(r):
    ctx = f"{r['ctx'] // 1000}k" if r["ctx"] else "-"
    out = f"{r['out']:.2f}" if r["out"] is not None else "-"
    caps = "".join([
        "V" if r["vision"] else "·",
        "T" if r["tools"] else "·",
        "S" if r["struct"] else "·",
        "!" if r["struct"] and not r["struct_all"] else " ",
    ])
    tps = f"{r['tps']:.0f}" if r["tps"] else "-"
    return f"| `{r['id']}` | {r['in']:.3f} | {out} | {ctx} | {caps} | {r['prov']} | {tps} |"


MARK_A = "<!-- CATALOGUE:START -->"
MARK_B = "<!-- CATALOGUE:END -->"


def main() -> int:
    write_to = None
    if "--write" in sys.argv:
        i = sys.argv.index("--write")
        if i + 1 >= len(sys.argv):
            print("--write needs a path", file=sys.stderr)
            return 2
        write_to = sys.argv[i + 1]

    rows = [s for s in (summarise(m) for m in json.load(sys.stdin).get("data", [])) if s]
    rows.sort(key=lambda r: r["in"])
    today = datetime.date.today().isoformat()

    out = []
    def emit(line=""):
        out.append(line)

    emit(f"<!-- generated by scripts/table.py on {today} — regenerate with `hf.sh table` -->")
    emit(f"\n{len(rows)} models on the router publish a price. Columns: **In/Out** = USD per 1M")
    emit("tokens at the *cheapest* provider; **Ctx** = largest context any provider offers;")
    emit("**Caps** = `V`ision / `T`ools / `S`tructured-output, and **`!` means at least one")
    emit("provider lacks structured output** — pin a provider for schema work; **Fastest**")
    emit("= best tok/s seen on any provider, which is usually *not* the cheapest one.\n")

    for title, lo, hi in TIERS:
        tier = [r for r in rows if lo <= r["in"] < hi]
        if not tier:
            continue
        emit(f"### {title} ({len(tier)})\n")
        emit("| Model | In | Out | Ctx | Caps | Cheapest on | Fastest |")
        emit("|---|--:|--:|--:|:--:|---|--:|")
        for r in tier:
            emit(fmt(r))
        emit()

    vision = [r for r in rows if r["vision"]]
    free = [r for r in rows if r["in"] == 0]
    emit(f"**{len(vision)} of {len(rows)} accept images.** "
          f"**{len(free)} are currently $0 in** (promos — never depend on one).")

    body = "\n".join(out)
    if not write_to:
        sys.stdout.write(body + "\n")
        return 0

    doc = open(write_to).read()
    if MARK_A not in doc or MARK_B not in doc:
        sys.stderr.write(f"{write_to}: missing {MARK_A} / {MARK_B} markers\n")
        return 1
    head, _, rest = doc.partition(MARK_A)
    _, _, tail = rest.partition(MARK_B)
    open(write_to, "w").write(f"{head}{MARK_A}\n{body}\n{MARK_B}{tail}")
    sys.stderr.write(f"{write_to}: catalogue refreshed ({len(rows)} models, {today})\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
